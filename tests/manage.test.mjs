import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import {once} from 'node:events';
import {createCustomerAuth} from '../integration/customer-auth.mjs';
import {createManageApi} from '../integration/manage-api.mjs';

test('management requires active staff, current permissions and channel access; buyers cannot read orders',async t=>{
 let role={isStaff:false,isActive:true,userPermissions:[],restrictedAccessToChannels:false,accessibleChannels:[]},reads=0,auth,manage;
 const json=(res,status,body)=>{res.writeHead(status,{'Content-Type':'application/json'});res.end(JSON.stringify(body));};
 const server=http.createServer(async(req,res)=>{const url=new URL(req.url,'http://localhost');if(!await auth.handle(req,res,url))await manage(req,res,url);});
 server.listen(0,'127.0.0.1');await once(server,'listening');t.after(()=>server.close());const base=`http://127.0.0.1:${server.address().port}`;
 const token=`h.${Buffer.from(JSON.stringify({exp:Math.floor(Date.now()/1000)+3600})).toString('base64url')}.private`;
 const user={id:'user-1',email:'test@example.com',firstName:'Тест',lastName:''};
 auth=createCustomerAuth({saleorUrl:'https://example.test/graphql',channel:'vs-market-ua',publicUrl:base,json,readBody:async req=>{let text='';for await(const chunk of req)text+=chunk;return JSON.parse(text);},fetchImpl:async(_,options)=>{
  const {query}=JSON.parse(options.body);
  const data=query.includes('CustomerLogin')?{tokenCreate:{token,user,errors:[]}}:{me:{...user,...role}};
  return {ok:true,json:async()=>({data})};
 }});
 manage=createManageApi({auth,orders:{setStatus:async()=>({status:'confirmed'}),list:async()=>{reads++;return [{order:{id:'test-order'},notifications:{email:{status:'pending'}}}];}},catalog:async()=>[],json,publicUrl:base,readBody:async()=>({}),channel:'vs-market-ua'});
 assert.equal((await fetch(base+'/api/manage/orders')).status,401);assert.equal(reads,0);
 const login=await fetch(base+'/api/auth/login',{method:'POST',headers:{Origin:base,'Content-Type':'application/json'},body:JSON.stringify({email:user.email,password:'password'})});
 const cookie=login.headers.get('set-cookie').split(';')[0];const get=action=>fetch(base+'/api/manage/'+action,{headers:{Cookie:cookie}});
 const toggle=(cookieValue=cookie,origin=base,type='application/json')=>fetch(base+'/api/manage/activation',{method:'POST',headers:{Cookie:cookieValue,Origin:origin,'Content-Type':type},body:'{}'});
 const edit=(cookieValue=cookie,origin=base)=>fetch(base+'/api/manage/edit',{method:'POST',headers:{Cookie:cookieValue,Origin:origin,'Content-Type':'application/json'},body:'{}'});
 const status=(origin=base)=>fetch(base+'/api/manage/order-status',{method:'POST',headers:{Cookie:cookie,Origin:origin,'Content-Type':'application/json'},body:'{}'});
 assert.equal((await status()).status,403);assert.equal((await status('https://untrusted.example')).status,403);
 assert.equal((await edit('')).status,401);assert.equal((await edit()).status,403);assert.equal((await edit(cookie,'https://untrusted.example')).status,403);assert.equal((await get('product')).status,403);
 assert.equal((await toggle('')).status,401);assert.equal((await toggle()).status,403);
 assert.equal((await toggle(cookie,'https://untrusted.example')).status,403);
 assert.equal((await toggle(cookie,base,'text/plain')).status,415);
 assert.equal((await get('orders')).status,403);assert.equal(reads,0);
 assert.equal((await get('interest')).status,403,'customer lists require customer management permission');
 assert.equal((await get('settings')).status,403,'settings require explicit permission');
 assert.equal((await get('notification-settings')).status,403,'notification secrets require settings permission');
 role.isStaff=true;assert.equal((await get('orders')).status,403);
 role.userPermissions=[{code:'MANAGE_ORDERS'}];
 assert.equal((await status()).status,200);
 assert.equal((await toggle()).status,403);
 const orders=await get('orders');assert.equal(orders.status,200);assert.equal((await orders.json()).records.length,1);
 assert.equal((await get('catalog')).status,403);
 const me=await(await get('me')).json();assert.equal(me.canOrders,true);assert.equal(me.canProducts,false);assert.equal(me.user.token,undefined);
 role.userPermissions=[];assert.equal((await get('orders')).status,403,'permissions are rechecked after login');
 role.userPermissions=[{code:'MANAGE_ORDERS'},{code:'MANAGE_PRODUCTS'}];role.restrictedAccessToChannels=true;
 assert.equal((await get('orders')).status,403);role.accessibleChannels=[{slug:'vs-market-ua'}];assert.equal((await get('catalog')).status,200);
 assert.equal((await toggle()).status,400,'valid staff still needs a valid model and boolean state');
 assert.equal((await edit()).status,400);assert.equal((await get('product')).status,400);
 role.isActive=false;assert.equal((await get('orders')).status,403);
 assert.equal((await fetch(base+'/api/manage/orders',{method:'POST',headers:{Cookie:cookie}})).status,405);
});
