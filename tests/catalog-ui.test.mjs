import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
test('catalog filters, recommendations and demo checkout preserve the buyer flow',async()=>{
 const elements=new Map();
 const element=key=>{
  if(!elements.has(key))elements.set(key,{value:'',textContent:'',innerHTML:'',hidden:true,dataset:{},style:{},listeners:{},classList:{add(){},remove(){},toggle(){return true}},addEventListener(name,fn){this.listeners[name]=fn},setAttribute(){},focus(){},scrollIntoView(){},querySelector(){return element('submit')},querySelectorAll(){return []}});
  return elements.get(key);
 };
 const rows=JSON.parse(await fs.readFile(new URL('../public/catalog-demo.json',import.meta.url),'utf8'));
 let checkoutUrl;
 const context=vm.createContext({document:{querySelector:element,querySelectorAll:()=>[],addEventListener(){},documentElement:{dataset:{theme:'dark'}},body:{style:{}}},location:{href:'http://localhost/?demo=1',search:'?demo=1',assign(url){checkoutUrl=url;}},localStorage:{getItem:()=>null,setItem(){}},URL,URLSearchParams,Intl,Date,Map,Set,matchMedia:()=>({matches:false}),fetch:async url=>{assert.equal(url,'/catalog-demo.json','demo only reads its local catalog');return {json:async()=>rows}}});
 vm.runInContext(await fs.readFile(new URL('../public/app.js',import.meta.url),'utf8'),context);
 await vm.runInContext('catalogReady',context);
 assert.match(element('#result-count').textContent,/8/);
 assert.match(element('#filter-groups').innerHTML,/Профіль/);
 assert.match(element('#filter-groups').innerHTML,/Колір/);
 vm.runInContext("state.facets['spec:width']=['950 мм']; state.facets['spec:color']=['Антрацит']; renderCatalog()",context);
 assert.match(element('#result-count').textContent,/2/);
 vm.runInContext("state.facets['spec:width']=['950 см']; renderCatalog()",context);
 assert.match(element('#product-grid').innerHTML,/товарів немає/,'units are not mixed');
 vm.runInContext("renderProduct(byId('demo-window-1'))",context);
 assert.match(element('#product-page').innerHTML,/Характеристики/);
 assert.match(element('#product-page').innerHTML,/Параметри демонстраційного товару ілюстративні/);
 vm.runInContext("state.products[0].specifications.push({key:'test',label:'<script>',value:'<img onerror=evil>',unit:'',filterable:true}); renderProduct(state.products[0]); renderFilters()",context);
 assert.match(element('#product-page').innerHTML,/&lt;img onerror=evil&gt;/);
 assert.match(element('#filter-groups').innerHTML,/&lt;script&gt;/);
 assert.doesNotMatch(element('#product-page').innerHTML,/<img onerror=evil>/);
 vm.runInContext("browse('Вікна')",context);
 assert.match(element('#result-count').textContent,/2/);
 vm.runInContext("state.category=''; state.facets.material=['Метал']; state.facets.opening=['Розпашне']; renderCatalog()",context);
 assert.match(element('#result-count').textContent,/2/);
 vm.runInContext("state.facets.material=['Дерево']; renderCatalog()",context);
 assert.match(element('#product-grid').innerHTML,/Міжкімнатні двері/);
 vm.runInContext("state.search='<script>'; renderCatalog()",context);
 assert.match(element('#product-grid').innerHTML,/товарів немає/);
 vm.runInContext("addProduct('demo-window-1')",context);
 assert.equal(element('#cart-count').textContent,1);
 assert.match(element('#cart-items').innerHTML,/>Видалити<\/button>/);
 assert.match(element('#cart-items').innerHTML,/class="cart-model-link" href="\/products\/demo-window-1\?demo=1"/);
 vm.runInContext("state.products[0].productId='model-1'; state.products[0].slug='selected-window'; renderCart()",context);
 assert.match(element('#cart-items').innerHTML,/href="\/products\/selected-window\?demo=1&amp;variant=demo-window-1"/,'cart link retains the exact variant');
 assert.match(element('#cart-suggestions').innerHTML,/Москітна сітка/);
 element('#checkout-button').listeners.click();
 assert.equal(checkoutUrl,'/checkout?demo=1','cart opens a separate page and retains demo mode');
});
